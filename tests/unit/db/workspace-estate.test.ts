/**
 * Keeps the bundled Workspace DO migration estate (src/server/objects/workspace/migrations/estate.generated.ts)
 * in step with `workspace.schema.ts`.
 *
 *   pnpm gen:workspace-estate               appends a state for the schema change (after the first deploy)
 *   ESTATE_FRESH=1 pnpm gen:workspace-estate  rebuilds one initial state (only before the first deploy)
 *
 * Without UPDATE_ESTATE the test only checks that the estate already holds the current schema.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, test } from 'vitest';
import { createMigrationClient } from 'viborm/migrations';
import { BundledEstate, emptyEstateDump } from '../../../src/server/db/driver/bundled-estate';
import { createDurableObjectSqliteClient } from '../../../src/server/db/driver/client';
import { WORKSPACE_TABLES, workspaceSchema } from '../../../src/server/db/workspace.schema';
import { workspaceEstate } from '../../../src/server/objects/workspace/migrations/estate.generated';

const FILE = fileURLToPath(
	new URL('../../../src/server/objects/workspace/migrations/estate.generated.ts', import.meta.url)
);

/** Generating is offline: the client never touches the (absent) storage. */
const offlineStorage = {
	sql: {
		exec() {
			throw new Error('generation is offline');
		}
	},
	transaction: async () => undefined
} as never;

describe('workspace migration estate', () => {
	test('holds the current schema (run `pnpm gen:workspace-estate` after a schema change)', async () => {
		const update = process.env.UPDATE_ESTATE === '1';
		const fresh = process.env.ESTATE_FRESH === '1';
		const storage = new BundledEstate(fresh ? emptyEstateDump() : workspaceEstate);
		const client = createDurableObjectSqliteClient(offlineStorage, workspaceSchema);
		const migrations = createMigrationClient(client, { storage, tables: WORKSPACE_TABLES });
		const result = await migrations.generate({ dryRun: !update, name: update ? 'workspace' : 'check' });
		if (update) {
			const source =
				"import type { EstateDump } from '../../../db/driver/bundled-estate';\n" +
				'/** Generated by `pnpm gen:workspace-estate`. Do not edit. */\n' +
				`export const workspaceEstate: EstateDump = ${JSON.stringify(storage.dump(), null, '\t')};\n`;
			writeFileSync(FILE, source);
			return;
		}
		expect(result.outcome, 'the schema changed: run `pnpm gen:workspace-estate`').toBe('noop');
	});
});
