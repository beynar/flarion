/**
 * Generates every theme artifact from `src/lib/design/notion.tokens.ts`.
 *
 *   pnpm gen:theme      (node --experimental-strip-types scripts/gen-theme.ts)
 *
 * Outputs, all in `src/lib/design/generated/` and committed:
 *   entasis-theme.css     the two `@plugin 'entasis/tailwind-plugin/theme'` blocks
 *   edytor-overrides.css  edytor's Notion theme tokens for light, and redefined for dark
 *   app-vars.css          `--app-*` variables plus fixes for what the theme engine can't express
 *   design-tokens.ts      the `<Theme designTokens>` map
 *
 * Theme-engine gaps and how this script closes them
 *   1. Non-monotonic surfaces. The sidebar is darker than the page in light mode and lighter in
 *      dark mode, and entasis derives its whole surface ladder from one seed by perceptual
 *      lightness. We pass every ladder step explicitly (recessed, canvas, raised, floating) and
 *      publish the sidebar as `--app-sidebar`, which the Sidebar's `theme` override reads.
 *   2. The base `surface` seed is always re-lightened (white becomes #fafafa, #191919 becomes
 *      about #111113), so a seed cannot give Notion's exact page color. app-vars.css therefore
 *      writes `--color-surface` directly.
 *   3. Exact shadows. `--elevation-3` (and 4 and 5, which dialogs use) carry Notion's three-layer
 *      menu shadow per theme, at `html[data-theme]` specificity, unlayered, so they beat both the
 *      plugin's base layer and `<Theme designTokens>`.
 *   5. Panel radius. `radius: 0.75` makes controls 6px and tags 3px but its `lg` step 9px; `--radius-lg` is written as the
 *      token's 10px for panels and menus.
 *   4. Row heights. entasis rows are 32/40/48 and controls 28/32/36. `--row-height-sm/md` are
 *      overridden to Notion's 28/36; button heights (28/24) share `--control-height-*` with
 *      inputs (32), so buttons get a `theme` override from `--app-button-height*` instead.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { blockColorNames, notion, type BlockColorName } from '../src/lib/design/notion.tokens.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'src/lib/design/generated');
mkdirSync(outDir, { recursive: true });

const HEADER = (what: string) =>
	`/* GENERATED by scripts/gen-theme.ts from src/lib/design/notion.tokens.ts. Do not edit.\n * ${what}\n */\n`;

type Theme = 'light' | 'dark';
const themes: Theme[] = ['light', 'dark'];
const { core, highContrast, shadows, blockColors, optionColors, type, metrics, radii, motion, entasis } = notion;

const px = (n: number) => `${n}px`;
const decls = (entries: Array<[string, string]>, indent = '\t') =>
	entries.map(([k, v]) => `${indent}${k}: ${v};`).join('\n');

/* ---------------------------------------------------------------- entasis-theme.css */

function entasisBlock(theme: Theme): string {
	const seeds = entasis[theme];
	const o = entasis.stateOpacity[theme];
	const surfaces: Array<[string, string]> = [
		// The whole ladder is explicit: see gap 1 in the header.
		['surface-recessed', core.sidebar[theme]],
		['surface-canvas', core.page[theme]],
		['surface-raised', core.surfaceRaised[theme]],
		['surface-floating', core.surfaceFloating[theme]]
	];
	const lines: Array<[string, string]> = [
		['name', theme],
		...(theme === 'light' ? ([['default', 'true']] as Array<[string, string]>) : []),
		['colorscheme', theme],
		...(theme === 'dark' ? ([['prefersDark', 'true']] as Array<[string, string]>) : []),
		['surface', seeds.surface],
		...surfaces,
		['neutral', seeds.neutral],
		['secondary', seeds.secondary],
		['primary', seeds.primary],
		// Notion's "on accent" is white; the engine would pick black for #2383e2.
		['primary-contrast', seeds['primary-contrast']],
		['info', seeds.info],
		['danger', seeds.danger],
		['danger-contrast', seeds['danger-contrast']],
		['success', seeds.success],
		['warning', seeds.warning],
		['state-hover-opacity', String(o.hover)],
		['state-pressed-opacity', String(o.pressed)],
		['state-selected-opacity', String(o.selected)],
		// md 6px for controls, sm 3px for tags. Read from the default block only.
		...(theme === 'light' ? ([['radius', String(entasis.radius)]] as Array<[string, string]>) : [])
	];
	return `@plugin 'entasis/tailwind-plugin/theme' {\n${decls(lines)}\n}\n`;
}

const entasisCss =
	HEADER('The entasis theme blocks. Imported by src/app.css.') +
	'\n' +
	themes.map(entasisBlock).join('\n');

/* ---------------------------------------------------------------- edytor-overrides.css */

function edytorVars(theme: Theme): Array<[string, string]> {
	const vars: Array<[string, string]> = [
		['--notion-text', core.text[theme]],
		['--notion-text-secondary', core.textSecondary[theme]],
		['--notion-placeholder', core.textTertiary[theme]],
		['--notion-border', core.hairline[theme]],
		['--notion-hover', core.hoverWash[theme]],
		['--notion-panel', core.calloutPanel[theme]],
		['--notion-code-panel', core.codePanel[theme]],
		['--notion-inline-code', core.inlineCode[theme]],
		['--notion-blue', core.accent[theme]],
		['--notion-text-selection', core.textSelection[theme]],
		['--notion-block-selection', core.blockSelection[theme]],
		['--notion-page', core.page[theme]],
		['--notion-font', type.fonts.sans.value],
		['--notion-mono', type.fonts.mono.value],
		['--edytor-nest-indent', px(metrics.nestStep.value)],
		['--edytor-drop-indicator-color', 'rgba(35, 131, 226, 0.43)'],
		['--edytor-drop-backdrop-color', core.blockSelection[theme]],
		['--edytor-marquee-background', core.blockSelection[theme]],
		['--edytor-code-background', core.codePanel[theme]],
		['--edytor-code-color', core.text[theme]],
		['--edytor-table-border', core.hairline[theme]],
		['--edytor-table-header-background', core.hoverWash[theme]]
	];
	for (const name of blockColorNames) {
		vars.push([`--edytor-color-${name}`, blockColors[name].text[theme]]);
	}
	for (const name of blockColorNames) {
		vars.push([`--edytor-background-${name}`, blockColors[name].background[theme]]);
	}
	return vars;
}

// edytor's own rule is `.edytor-notion` (0,1,0). `html .edytor-notion` (0,1,1) wins whatever the
// import order; the dark selector is more specific still. The theme is light-only, so dark
// redefines every token.
const edytorCss =
	HEADER("edytor's Notion theme tokens (light) and their dark redefinition.") +
	'\n' +
	`html .edytor-notion {\n${decls(edytorVars('light'))}\n}\n\n` +
	`html[data-theme='dark'] .edytor-notion {\n${decls(edytorVars('dark'))}\n}\n`;

/* ---------------------------------------------------------------- app-vars.css */

function appThemeVars(theme: Theme): Array<[string, string]> {
	const v: Array<[string, string]> = [
		['--app-page', core.page[theme]],
		['--app-sidebar', core.sidebar[theme]],
		['--app-text', core.text[theme]],
		['--app-text-secondary', core.textSecondary[theme]],
		['--app-text-tertiary', core.textTertiary[theme]],
		['--app-text-sidebar', core.textSidebar[theme]],
		['--app-hairline', core.hairline[theme]],
		['--app-hairline-strong', core.hairlineStrong[theme]],
		['--app-hover', core.hoverWash[theme]],
		['--app-active', core.activeRow[theme]],
		['--app-input-fill', core.inputFill[theme]],
		['--app-accent', core.accent[theme]],
		['--app-danger', core.danger[theme]],
		['--app-callout', core.calloutPanel[theme]],
		['--app-code-panel', core.codePanel[theme]],
		['--app-scrim', core.scrim[theme]],
		['--app-shadow-menu', shadows.menu[theme]],
		['--app-shadow-card', shadows.card[theme]],
		['--app-shadow-button', shadows.button[theme]],
		// Gap 2: the engine re-lightens the `surface` seed, so write the exact page color.
		['--color-surface', core.page[theme]],
		// Gap 3: Notion's menu shadow on every floating level, with no dark-mode tonal tint.
		['--elevation-3', shadows.menu[theme]],
		['--elevation-4', shadows.menu[theme]],
		['--elevation-5', shadows.menu[theme]],
		['--elevation-tint-3', 'transparent'],
		['--elevation-tint-4', 'transparent'],
		['--elevation-tint-5', 'transparent']
	];
	for (const name of blockColorNames) {
		v.push([`--app-option-${name}-bg`, optionColors[name].background[theme]]);
		v.push([`--app-option-${name}-fg`, optionColors[name].text[theme]]);
		v.push([`--app-block-${name}`, blockColors[name].text[theme]]);
		v.push([`--app-block-${name}-bg`, blockColors[name].background[theme]]);
	}
	return v;
}

